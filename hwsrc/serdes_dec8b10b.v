// 8b/10b 译码的查表那一半：code 是 {a,b,c,d,e,i,f,g,h,j}。组合逻辑。
// 这里只管把码字翻回字节，并报出表里根本没有的六位码、四位码。码字在当前游程差下合不合法，
// 由接收端把译出的字节重新编码、与收到的码字比对来判（serdes_rx），不在这里另列一套规则。
module serdes_dec8b10b (
  input  wire [9:0] code,
  output wire [7:0] d,
  output wire       k,
  output wire       bad
);
  wire [5:0] c6 = code[9:4];
  wire [3:0] c4 = code[3:0];

  reg [4:0] x;
  reg       k28;
  reg       bad6;
  always @* begin
    k28 = 1'b0;
    bad6 = 1'b0;
    case (c6)
      6'b100111, 6'b011000: x = 5'd0;
      6'b011101, 6'b100010: x = 5'd1;
      6'b101101, 6'b010010: x = 5'd2;
      6'b110001:            x = 5'd3;
      6'b110101, 6'b001010: x = 5'd4;
      6'b101001:            x = 5'd5;
      6'b011001:            x = 5'd6;
      6'b111000, 6'b000111: x = 5'd7;
      6'b111001, 6'b000110: x = 5'd8;
      6'b100101:            x = 5'd9;
      6'b010101:            x = 5'd10;
      6'b110100:            x = 5'd11;
      6'b001101:            x = 5'd12;
      6'b101100:            x = 5'd13;
      6'b011100:            x = 5'd14;
      6'b010111, 6'b101000: x = 5'd15;
      6'b011011, 6'b100100: x = 5'd16;
      6'b100011:            x = 5'd17;
      6'b010011:            x = 5'd18;
      6'b110010:            x = 5'd19;
      6'b001011:            x = 5'd20;
      6'b101010:            x = 5'd21;
      6'b011010:            x = 5'd22;
      6'b111010, 6'b000101: x = 5'd23;
      6'b110011, 6'b001100: x = 5'd24;
      6'b100110:            x = 5'd25;
      6'b010110:            x = 5'd26;
      6'b110110, 6'b001001: x = 5'd27;
      6'b001110:            x = 5'd28;
      6'b101110, 6'b010001: x = 5'd29;
      6'b011110, 6'b100001: x = 5'd30;
      6'b101011, 6'b010100: x = 5'd31;
      6'b001111, 6'b110000: begin x = 5'd28; k28 = 1'b1; end
      default:              begin x = 5'd0; bad6 = 1'b1; end
    endcase
  end

  // K28 的四位码在六位码取反的那一种写法（110000）之后，.1 与 .6、.2 与 .5 的码字对调
  wire swap = c6 == 6'b110000;

  reg [2:0] y;
  reg       bad4;
  always @* begin
    bad4 = 1'b0;
    case (c4)
      4'b1011, 4'b0100: y = 3'd0;
      4'b1001:          y = swap ? 3'd6 : 3'd1;
      4'b0101:          y = swap ? 3'd5 : 3'd2;
      4'b1100, 4'b0011: y = 3'd3;
      4'b1101, 4'b0010: y = 3'd4;
      4'b1010:          y = swap ? 3'd2 : 3'd5;
      4'b0110:          y = swap ? 3'd1 : 3'd6;
      4'b1110, 4'b0001,
      4'b0111, 4'b1000: y = 3'd7;
      default:          begin y = 3'd0; bad4 = 1'b1; end
    endcase
  end

  wire a7 = c4 == 4'b0111 || c4 == 4'b1000;
  assign d = {y, x};
  assign k = k28 || (a7 && (x == 5'd23 || x == 5'd27 || x == 5'd29 || x == 5'd30));
  assign bad = bad6 || bad4;
endmodule
